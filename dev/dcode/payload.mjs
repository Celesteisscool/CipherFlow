/* dCode module payload generator ---------------------------------------------------
 * Turns the operation specs in dev/dcode/ops-*.mjs into the plain script the
 * CyberChef worker evaluates at runtime (see the host hook in dev/build.mjs). The
 * same text is what dev/dcode/selftest.mjs runs in Node, so a cipher can be
 * exercised without launching a browser.
 *
 * The payload has to be self-contained: it may not import anything, because it is
 * delivered to the worker as a string and run with an indirect eval. Operation
 * bodies therefore reference the helpers from dev/dcode/runtime.js, which are
 * embedded at the top of the same script.
 */
import fs from "node:fs";
import * as shift from "./ops-shift.mjs";
import * as transposition from "./ops-transposition.mjs";
import * as polygrammic from "./ops-polygrammic.mjs";
import * as text from "./ops-text.mjs";
import * as magic from "./ops-magic.mjs";

export const MODULE_NAME = "CipherFlowDcode";
export const BATCHES = [shift, transposition, polygrammic, text, magic];
// Helper files are concatenated in order; every `run` may use all of them.
export const RUNTIME_FILES = ["runtime.js", "runtime-transposition.js", "runtime-polygrammic.js", "runtime-text.js"];

export function allOps() {
    return BATCHES.flatMap(batch => batch.ops || []);
}
export function allPairs() {
    return BATCHES.flatMap(batch => batch.pairs || []);
}
export function allChecks() {
    return BATCHES.flatMap(batch => batch.checks || []);
}

function fnSource(fn) {
    const src = String(fn);
    // Method shorthand ("run(input, args) { ... }") is valid as-is inside an object;
    // anything else keeps its own syntax. Both are inserted verbatim.
    return src;
}

export function renderModule() {
    const runtime = RUNTIME_FILES
        .map(file => fs.readFileSync(new URL("./" + file, import.meta.url), "utf8"))
        .join("\n");
    const specs = allOps().map(spec => ({
        name: spec.name,
        group: spec.group,
        description: spec.description,
        args: spec.args || [],
        run: fnSource(spec.run)
    }));
    return `/* CipherFlow dCode operations — generated by dev/dcode/payload.mjs. Do not edit. */
(function () {
'use strict';
${runtime}
var CF_MODULE = ${JSON.stringify(MODULE_NAME)};
var CF_SPECS = [
${specs.map(spec => `    {
        name: ${JSON.stringify(spec.name)},
        group: ${JSON.stringify(spec.group)},
        description: ${JSON.stringify(spec.description)},
        args: ${JSON.stringify(spec.args)},
        run: ${spec.run}
    }`).join(",\n")}
];
var CF_REGISTRY = (self.OpModules = self.OpModules || {});
var CF_CONFIG = (self.OperationConfig = self.OperationConfig || {});
// Inherit the engine's own Operation base class when it is present, so
// presentType/present() and the argument plumbing behave exactly like the
// built-in operations. The Node self-test has no engine loaded and falls back to
// a minimal stand-in.
var CF_Base = (function () {
    try {
        var modules = CF_REGISTRY.Default || {};
        var names = Object.keys(modules);
        for (var i = 0; i < names.length; i++) {
            var cls = modules[names[i]];
            if (typeof cls !== "function") continue;
            var parent = Object.getPrototypeOf(cls);
            if (typeof parent === "function" && parent !== Function.prototype) return parent;
        }
    } catch (err) { /* fall through to the stand-in */ }
    return class {
        present(value) { return value; }
    };
})();
function cfMakeClass(spec) {
    return class CipherFlowDcodeOp extends CF_Base {
        constructor() {
            super();
            this.name = spec.name;
            this.module = CF_MODULE;
            this.inputType = "string";
            this.outputType = "string";
            this.args = spec.args;
        }
        run(input, args) {
            return spec.run(String(input == null ? "" : input), args || []);
        }
    };
}
var CF_CLASSES = {};
for (var s = 0; s < CF_SPECS.length; s++) {
    var spec = CF_SPECS[s];
    CF_CLASSES[spec.name] = cfMakeClass(spec);
    CF_CONFIG[spec.name] = {
        module: CF_MODULE,
        name: spec.name,
        description: spec.description,
        inputType: "string",
        outputType: "string",
        args: spec.args,
        flowControl: false
    };
}
CF_REGISTRY[CF_MODULE] = CF_CLASSES;
})();
`;
}
