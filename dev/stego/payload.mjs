/* CipherFlow steganography module generator ----------------------------------
 * Turns dev/stego/ops.mjs plus the support tables into the plain script the
 * CyberChef worker evaluates at runtime, the same way dev/dcode/payload.mjs does
 * for the text operations. The payload must be self-contained: operation bodies
 * are delivered as text and may not import, so the runtime and its tables are
 * concatenated ahead of the operation classes.
 *
 * The generated module is committed only through assets/CipherFlowStego.js after
 * `node dev/build.mjs`; the dev/modules copy is a build input and is not committed.
 */
import fs from "node:fs";
import {ops} from "./ops.mjs";

export const MODULE_NAME = "CipherFlowStego";
// Order matters only in that runtime.js reads the tables at call time, not load time.
export const RUNTIME_FILES = ["ltable.js", "blowfish-tables.js", "jpeg-coeff.js", "runtime.js"];

export function allOps() {
    return ops;
}

export function renderModule(options = {}) {
    const runtime = RUNTIME_FILES
        .map(file => fs.readFileSync(new URL("./" + file, import.meta.url), "utf8"))
        .join("\n");
    const specs = allOps().map(spec => ({
        name: spec.name,
        group: spec.group,
        description: spec.description,
        args: spec.args || [],
        run: String(spec.run)
    }));
    const internals = options.exposeInternals ? `
// Self-test hook: never present unless dev/stego/selftest.mjs asks for it.
self.CipherFlowStegoTest = {
    md5: CF_STEGO.md5,
    desDecryptBlock: CF_STEGO.desDecryptBlock,
    desSubkeys: CF_STEGO.desSubkeys,
    pbeDecrypt: CF_STEGO.pbeDecrypt,
    javaRandom: CF_STEGO.javaRandom,
    passwordSeed: CF_STEGO.passwordSeed,
    openStegoFromRgba: CF_STEGO.openStegoFromRgba,
    extractStegoShare: CF_STEGO.extractStegoShare,
    stegoshareKey: CF_STEGO.stegoshareKey,
    stegoshareReadImage: CF_STEGO.stegoshareReadImage,
    stegoshareAssemble: CF_STEGO.stegoshareAssemble,
    jphideFromCoefficients: CF_STEGO.jphideFromCoefficients,
    jphideV05FromCoefficients: CF_STEGO.jphideV05FromCoefficients,
    jphideV05Pass: CF_STEGO.jphideV05Pass,
    jphideFromJpeg: CF_STEGO.jphideFromJpeg,
    lzo1xDecompress: CF_STEGO.lzo1xDecompress,
    bfExpandKey: CF_STEGO.bfExpandKey,
    bfEncryptBytes: CF_STEGO.bfEncryptBytes,
    bfDecryptBytes: CF_STEGO.bfDecryptBytes,
    bfDecryptNativeLE: CF_STEGO.bfDecryptNativeLE
};
` : "";
    return `/* CipherFlow steganography operations — generated by dev/stego/payload.mjs. Do not edit. */
(function () {
'use strict';
${runtime}
var CF_MODULE = ${JSON.stringify(MODULE_NAME)};
var CF_SPECS = [
${specs.map(spec => `    {
        name: ${JSON.stringify(spec.name)},
        group: ${JSON.stringify(spec.group)},
        description: ${JSON.stringify(spec.description)},
        args: ${JSON.stringify(spec.args)},
        run: ${spec.run}
    }`).join(",\n")}
];
var CF_REGISTRY = (self.OpModules = self.OpModules || {});
var CF_CONFIG = (self.OperationConfig = self.OperationConfig || {});
// Inherit the engine's own Operation base class when it is present, so the
// argument plumbing and presentation behave like a built-in operation. The Node
// self-test has no engine loaded and falls back to a minimal stand-in.
var CF_Base = (function () {
    try {
        var modules = CF_REGISTRY.Default || {};
        var names = Object.keys(modules);
        for (var i = 0; i < names.length; i++) {
            var cls = modules[names[i]];
            if (typeof cls !== "function") continue;
            var parent = Object.getPrototypeOf(cls);
            if (typeof parent === "function" && parent !== Function.prototype) return parent;
        }
    } catch (err) { /* fall through to the stand-in */ }
    return class {
        present(value) { return value; }
    };
})();
function cfMakeClass(spec) {
    return class CipherFlowStegoOp extends CF_Base {
        constructor() {
            super();
            this.name = spec.name;
            this.module = CF_MODULE;
            this.inputType = "ArrayBuffer";
            this.outputType = "byteArray";
            this.args = spec.args;
        }
        run(input, args) {
            return spec.run(input, args || []);
        }
    };
}
var CF_CLASSES = {};
for (var s = 0; s < CF_SPECS.length; s++) {
    var spec = CF_SPECS[s];
    CF_CLASSES[spec.name] = cfMakeClass(spec);
    CF_CONFIG[spec.name] = {
        module: CF_MODULE,
        name: spec.name,
        description: spec.description,
        inputType: "ArrayBuffer",
        outputType: "byteArray",
        args: spec.args,
        flowControl: false
    };
}
CF_REGISTRY[CF_MODULE] = CF_CLASSES;
${internals}})();
`;
}
